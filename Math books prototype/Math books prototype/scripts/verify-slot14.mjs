// (2) A_a ⊂ A_2 이고 A_b ⊂ A_3 이며 A_a ∪ A_b = A_2 ∪ A_3 인 (a,b)의 순서쌍의 개수  (BW 역방향)
// (3) A_k ∩ A_18 = A_36 이고 k ≤ 100 인 자연수 k의 개수  (PD 패턴)
//
// 원리: A_m ⊂ A_n ⇔ n | m (n이 m의 약수)
// A_a ∩ A_b = A_{lcm(a,b)}
// A_a ∪ A_b는 배수집합이 아닐 수 있으나, 여기서 조건에 맞게 설계

// (1): A_3 ∩ A_5 = A_15
console.log("[(1)] A_3 ∩ A_5 = A_lcm(3,5) = A_15");

// (2): A_a ⊂ A_2 ⇔ 2|a. A_b ⊂ A_3 ⇔ 3|b.
// A_a ∪ A_b = A_2 ∪ A_3 = (2의 배수) ∪ (3의 배수)
// A_a는 2|a이므로 A_a ⊂ A_2. A_b도 3|b이므로 A_b ⊂ A_3.
// A_a ∪ A_b = A_2 ∪ A_3이 되려면 A_a = A_2 이고 A_b = A_3.
//   즉 a=2, b=3. 순서쌍 (2,3) 하나뿐?
// 아니, A_a ⊆ A_2 이지만 A_a = A_2가 아닌 경우, A_a ∪ A_b 안에 A_2 - A_a 원소가 없음.
// 예: a=4일 때 A_4 ⊂ A_2. A_4 ∪ A_b에는 2 자체가 없을 수 있음.
// A_2의 원소 2가 A_a ∪ A_b에 있으려면 2 ∈ A_a (즉 a=1 or 2) 또는 2 ∈ A_b.
//   2|a 이므로 a=2 (a=1은 불가, 2|1 아님).
// 마찬가지로 3 ∈ A_2 ∪ A_3 이므로 3 ∈ A_a ∪ A_b. 3 ∈ A_a ⇔ a|3, 그런데 2|a 이므로 a=6 이상 필요, 안됨.
// 3 ∈ A_b ⇔ b|3, 3|b 이므로 b=3.
// 결론: (a,b) = (2, 3) 유일.
// → 답이 너무 간단. 조건 재설계.

// 재설계 (2):
// A_a ⊂ A_2, A_b ⊂ A_3, A_a ∪ A_b ⊃ {6, 12, 18, ..., 60까지의 원소}
// 너무 복잡. 다른 방향:
//
// (2') A_a ∩ A_b = A_12 인 (a,b)의 순서쌍 (a<b, a≤10, b≤20)  [PD·BW]
// A_a ∩ A_b = A_lcm(a,b) = A_12 ⇔ lcm(a,b) = 12
// a<b, a|12, b|12, lcm(a,b)=12
// (a,b)의 순서쌍: 12=2^2 * 3. a·b의 lcm=12.
// {1,2,3,4,6,12} 중에서 lcm(a,b)=12
// (1,12), (2,12), (3,12), (4,12), (6,12), (3,4), (4,6), (4,12: dup) ...
// 세부: a≤b, lcm=12: (1,12), (2,12), (3,4), (3,12), (4,6), (4,12), (6,12)
// 순서쌍 개수 (a≤b) = 7
console.log("\n[(2)] A_a ∩ A_b = A_12 (a≤b, a·b 자연수)의 (a,b) 개수:");
let count = 0;
for (let a = 1; a <= 12; a++) {
  for (let b = a; b <= 12; b++) {
    if (12 % a === 0 && 12 % b === 0) {
      const gcd = (x,y) => y ? gcd(y, x%y) : x;
      const lcm = a * b / gcd(a, b);
      if (lcm === 12) {
        count++;
        console.log(`  (${a},${b})`);
      }
    }
  }
}
console.log(`  총 개수 = ${count}`);

// (3): A_k ⊂ A_12 이고 A_k ∪ A_18 = A_6 인 자연수 k (k≤100)의 개수
// A_k ⊂ A_12 ⇔ 12|k
// A_18의 원소는 18의 배수 = {18, 36, 54, 72, ...}
// A_6 = {6, 12, 18, 24, 30, 36, ...}
// A_k ∪ A_18 = A_6 ⇔ A_k ∪ A_18 = 6의 배수 전체
// 그런데 A_k ⊂ A_12 이므로 A_k는 12의 배수만 있음.
// A_k ∪ A_18 이 A_6 전체(6, 12, 18, ...)를 포함하려면
//   6이 A_k∪A_18 에 있어야 → 6 ∈ A_k (k|6, k∈{1,2,3,6}) 또는 6 ∈ A_18 (No)
//   그런데 12|k 이므로 k≥12. → 6 ∈ A_k 불가.
// 조건 불가. 재설계.

// 재설계 (3'): A_k ∩ A_18 = A_36 인 k (k≤100)
// lcm(k, 18) = 36 이 되도록.
// k | 36, 18 | 36 ✓. lcm(k, 18) = 36.
// k의 후보 (36의 약수): {1,2,3,4,6,9,12,18,36}
// lcm(k, 18) = 36:
//   lcm(1,18)=18. No
//   lcm(2,18)=18. No
//   lcm(3,18)=18. No
//   lcm(4,18)=36. Yes
//   lcm(6,18)=18. No
//   lcm(9,18)=18. No
//   lcm(12,18)=36. Yes
//   lcm(18,18)=18. No
//   lcm(36,18)=36. Yes
// k ∈ {4, 12, 36} 그런데 문제는 A_k ∩ A_18 = A_lcm(k,18) 이라 이건 lcm 정의만 있음.
// 그런데 문제는 "A_k ∩ A_18 = A_36 이고 k ≤ 100 인 자연수 k의 개수"
// 여기서 k는 36의 약수여야 하나? lcm(k,18)=36 이어야 함.
// k>36인 경우: lcm(k,18)≥k>36. 안됨.
// 따라서 k ∈ {4, 12, 36}. k≤100 자동 성립. 답: 3

console.log("\n[(3)] A_k ∩ A_18 = A_36 (k≤100) 인 자연수 k:");
const gcd = (x,y) => y ? gcd(y, x%y) : x;
let count3 = 0;
const ks = [];
for (let k = 1; k <= 100; k++) {
  const lcm = k * 18 / gcd(k, 18);
  if (lcm === 36) {
    count3++;
    ks.push(k);
  }
}
console.log(`  k ∈ {${ks.join(', ')}} → 개수 = ${count3}`);

