    const L = lines[i];
    if (봐주는줄.test(L) || 인용줄.test(L)) continue;
    // 🔴 파일 이름 안의 옛말은 낱말 사용이 아니다 — `실행부담-읽을양-재정리-v1.md` 는 실재하는 파일명이다.
