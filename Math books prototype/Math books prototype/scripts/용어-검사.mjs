/** 도구가 **화면에 찍는** 문자열만 본다. 변수명·주석은 안 본다 */
function 도구검사(dir) {
  let files = [];
  try { files = fs.readdirSync(R(dir)).filter((f) => f.endsWith('.mjs')); } catch { return; }
  for (const f of files) {
    const rel = `${dir}/${f}`;
    const 전문 = fs.readFileSync(R(rel), 'utf8');
    // 🔴 머리에 폐기 표시가 달린 도구는 통째로 봐준다 — 접은 점수 체계를 기록으로 남긴 것이다
    if (/〔폐기\s*\d{4}-\d{2}-\d{2}〕/.test(전문.split(/\r?\n/).slice(0, 8).join('\n'))) continue;
    const lines = 전문.split(/\r?\n/);
    for (let i = 0; i < lines.length; i++) {
      const L = lines[i];
      if (!/console\.(log|error)/.test(L)) continue;
      if (봐주는줄.test(L) || 인용줄.test(L)) continue;
      // 🔴 `${r.qid}` 같은 **변수 이름**은 화면에 안 찍힌다 — 값이 찍힌다. 헛것을 잡지 않도록 지운다.
      //    (2026-08-02: 이걸 안 지웠더니 검사기가 헛것 셋을 잡았다. 헛것을 잡으면 사람이 안 본다.)
      // 파일 이름 안의 영어는 코드명이 아니다 (`graph-position-audit.mjs` 의 position 등)
      const 찍히는것 = L.replace(/\$\{[^}]*\}/g, '').replace(/[\w.-]+\.(mjs|tex|md|json|csv)/g, '');
      // 화면에 코드명을 그대로 찍는가
      if (/['"`][^'"`]*\b(qid|rater|nearest|position|band)\b/.test(찍히는것)) {
        결과.push({ 곳: `${rel}:${i + 1}`, 이름: '영문 코드명', 대신: '문항 · 판정자 · 가장 가까운 앵커', 줄: L.trim().slice(0, 70) });
      }
      for (const g of 금지) {
        if (g.말.test(L)) 결과.push({ 곳: `${rel}:${i + 1}`, 이름: g.이름, 대신: g.대신, 줄: L.trim().slice(0, 70) });
      }
    }
  }
}

