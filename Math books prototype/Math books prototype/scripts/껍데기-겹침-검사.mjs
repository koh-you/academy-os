/**
 * 껍데기 겹침 검사 — 도구 이름이 달라도 겉꼴이 같으면 잡는다
 *
 * 🔴 왜 만들었나 (2026-08-05 세션 115)
 *   재현-2회에서 7번과 11번이 **층·정답·선지까지 같은 문항**이 됐다.
 *   문항마다 붙은 제안자 셋이 다 「도구가 다르다」고 **옳게** 보고했다 —
 *   7번은 세 직선, 11번은 대칭이동이었다. 맞는 말인데 껍데기가 같았다.
 *   대조표에 「도구」 칸밖에 없어 **도구 이름만 다르면 통과**했다.
 *   🔴 이 도구는 **겉꼴**을 센다. 도구는 안 본다.
 *
 *   같은 판에서 잡힌 것 셋도 함께 본다 —
 *     · 선지가 관문을 대신 넘겨준다 (5·8번 — 선지 다섯이 같은 말로 시작했다)
 *     · 재료 쏠림 (원이 여섯 문항 41.6점)
 *     · 발문 끝말 뭉침 (「모두 구하시오」 일곱 번)
 *
 * 쓰는 법
 *   node scripts/껍데기-겹침-검사.mjs <문제.tex>
 *   node scripts/껍데기-겹침-검사.mjs <답지.tex>     ← 제목(출제의도) 말투를 본다
 *
 * 🔴 이 도구는 「닮았다」고만 말한다. 같은 문항인지는 사람이 판정한다.
 */
import fs from 'node:fs';
import path from 'node:path';

const 파일 = process.argv[2];
if (!파일) { console.error('사용: node scripts/껍데기-겹침-검사.mjs <파일.tex>'); process.exit(2); }
const 원문 = fs.readFileSync(파일, 'utf8');
const 이름 = path.basename(파일);
const 답지인가 = /dmsoltitle/.test(원문);

let RED = 0, YELLOW = 0;
const 말 = (s) => console.log(s);
const 빨강 = (s) => { RED++; console.log(`🔴 ${s}`); };
const 노랑 = (s) => { YELLOW++; console.log(`🟡 ${s}`); };

말(`\n껍데기 겹침 검사 — ${이름}`);
말('도구가 아니라 겉꼴을 센다. 도구 이름이 달라도 겉꼴이 같으면 같은 문항으로 읽힌다.');
말('='.repeat(74));

// ══════════════════════════════════════════════════════════════════════════
// 답지 — 제목(출제의도) 말투
// ══════════════════════════════════════════════════════════════════════════
if (답지인가) {
  말('\n── 제목(출제의도) 말투 ────────────────────────────────────────────────');
  말('🔴 이 칸은 검수 그물에 없던 자리다. 세션 115 에 마스터가 직접 잡았다.');
  const 제목 = [...원문.matchAll(/\\dmsoltitle\{(\d+)\}\{((?:[^{}]|\{[^{}]*\})*)\}/g)]
    .map((m) => [m[1], m[2]]);
  말(`   제목 ${제목.length} 개`);

  // (가) 문장으로 끝나는가 — 골든은 전부 명사형이다
  const 서술어끝 = /(한다|된다|이다|난다|본다|간다|온다|준다|짚는다|정한다|나뉜다)\s*$/;
  for (const [n, t] of 제목) {
    if (서술어끝.test(t.replace(/\\\s/g, ''))) 빨강(`${이름} · ${n}번 제목이 문장으로 끝난다 — 골든은 전부 명사형이다\n     「${t}」`);
  }

  // (나) 설계 논의에서 쓰던 비유가 새어 나왔는가
  //   🔴 세션 115 실제 사례 — 「울타리」·「갈래를 연다」·「모순을 세운다」·「가장 센/헐거운 것」
  const 비유 = ['울타리', '갈래를 열', '갈래를 연', '모순을 세우', '가장 센 것', '가장 헐거운 것',
                '껍데기', '되짚기 자리', '관문을 연', '덫을 놓'];
  const 줄 = 원문.split(/\r?\n/);
  for (const w of 비유) {
    줄.forEach((L, i) => {
      if (L.trim().startsWith('%')) return;
      if (L.includes(w)) 빨강(`${이름}:${i + 1} 설계 논의의 비유가 본문에 있다 — 「${w}」\n     ${L.trim().slice(0, 70)}`);
    });
  }
  if (RED === 0) 말('   ✅ 제목이 다 명사형이고 지어낸 비유도 없다');
}

// ══════════════════════════════════════════════════════════════════════════
// 시험지 — 문항의 겉꼴
// ══════════════════════════════════════════════════════════════════════════
if (!답지인가) {
  // 문항을 통째로 자른다 — 🔴 경계는 문항 번호로 잡는다 (매크로 이름으로 잡지 마라 · 세션 109 사고)
  const 줄 = 원문.split(/\r?\n/);
  const 문항 = [];
  for (let i = 0; i < 줄.length; i++) {
    const m = 줄[i].match(/\\begin\{problem\}\{(\d+)\}/);
    if (!m) continue;
    let 끝 = i;
    while (끝 < 줄.length && !/\\begin\{problem\}\{\d+\}/.test(줄[끝 + 1] || '') && 끝 < 줄.length - 1) {
      끝++;
      if (/\\end\{pagepair\}/.test(줄[끝])) break;
    }
    const 몸 = 줄.slice(i, 끝 + 1).filter((L) => !L.trim().startsWith('%')).join('\n');
    문항.push({ n: Number(m[1]), 몸 });
    i = 끝;
  }
  문항.sort((a, b) => a.n - b.n);
  말(`\n   문항 ${문항.length} 개를 읽었다`);

  // ── (1) 선지가 관문을 흘리는가 ────────────────────────────────────────
  말('\n── 선지가 관문을 흘리는가 ─────────────────────────────────────────────');
  말('🔴 발문이 안 하는 말을 선지가 하면 발문이 흘린 것과 같다 (세션 115 · 5·8번).');
  for (const { n, 몸 } of 문항) {
    // choicesv / choicesii / choices32 의 다섯 인자, 또는 \choice{} 다섯
    let 선지 = [...몸.matchAll(/\\choice\{((?:[^{}]|\{[^{}]*\})*)\}/g)].map((m) => m[1]);
    if (선지.length !== 5) {
      const b = 몸.match(/\\begin\{choices(?:32|ii|v)\}([\s\S]*?)\\end\{choices(?:32|ii|v)\}/);
      if (b) {
        const 것 = []; let s = b[1], i = 0;
        while (것.length < 5) {
          while (s[i] === '%' || s[i] === '\n' || s[i] === ' ') i++;
          if (s[i] !== '{') break;
          let d = 0, j = i;
          for (; j < s.length; j++) { if (s[j] === '{') d++; else if (s[j] === '}') { d--; if (!d) break; } }
          것.push(s.slice(i + 1, j)); i = j + 1;
        }
        선지 = 것;
      }
    }
    if (선지.length !== 5) continue;
    // 앞부분이 같은 선지가 셋 이상이면 그 부분이 공짜로 주어진다
    // 🔴 다만 LaTeX 명령만 같은 것은 세지 않는다 — 선지 넷이 \dfrac 으로 시작하는 것은
    //    「분수다」라는 형식일 뿐 내용을 안 흘린다. 5번의 「-3\le a<」 와는 다르다.
    const 알맹이 = (s) => s.replace(/\s/g, '').replace(/\\[a-zA-Z]+/g, '').replace(/[{}$]/g, '');
    const 머리 = 선지.map((x) => 알맹이(x).slice(0, 6));
    const 표 = {};
    머리.forEach((h) => { if (h.length >= 3) 표[h] = (표[h] || 0) + 1; });
    for (const [h, c] of Object.entries(표)) {
      if (c >= 3) 빨강(`${n}번 — 선지 ${c} 개가 「${h}…」로 시작한다. 그 부분이 학생에게 공짜로 넘어간다`);
    }
  }
  if (RED === 0) 말('   ✅ 선지가 앞부분을 흘리는 문항 없음');

  // ── (2) 보기형 겉꼴이 겹치는가 ────────────────────────────────────────
  말('\n── 보기형 겉꼴 ────────────────────────────────────────────────────────');
  const 보기형 = 문항.filter((x) => /bogibox/.test(x.몸));
  말(`   보기형 ${보기형.length} 문 — ${보기형.map((x) => x.n).join(' · ') || '없음'}`);
  if (보기형.length >= 2) {
    노랑(`보기형이 ${보기형.length} 문이다. 🔴 층(ㄱㄴㄷ 각각의 참·거짓)과 정답 조합이 같은지 **눈으로** 보라.\n     세션 115 에 7번과 11번이 층·정답·선지까지 같았는데 아무도 못 잡았다`);
  }

  // ── (3) 발문 끝말 뭉침 ────────────────────────────────────────────────
  말('\n── 발문 끝말 ──────────────────────────────────────────────────────────');
  const 끝말 = { '모두 구하시오': 0, '최댓값': 0, '최솟값': 0, '값의 합': 0, '값의 범위': 0, '개수': 0 };
  for (const { 몸 } of 문항) for (const k of Object.keys(끝말)) if (몸.includes(k)) 끝말[k]++;
  for (const [k, c] of Object.entries(끝말)) {
    const 표시 = c >= 6 ? '🔴' : c >= 4 ? '🟡' : '  ';
    말(`   ${표시} 「${k}」 ${c} 문`);
    if (c >= 6) RED++; else if (c >= 4) YELLOW++;
  }
  말('   임계 — 4 문이면 🟡 · 6 문이면 🔴 (열일곱 중 셋을 넘으면 말이 뭉쳐 보인다)');

  // ── (4) 재료 쏠림 — 🔴 자동으로 못 센다. 대조표에 칸이 있는지만 본다 ──
  말('\n── 재료 쏠림 ──────────────────────────────────────────────────────────');
  말('🔴 세션 115 — 1회의 「두 원 관계를 줄인다」는 지켰는데 원 자체는 여섯 문항이 됐다.');
  말('   글자대로 지키고 뜻을 놓친 자리다.');
  말('🔴 **이 칸은 기계가 못 센다.** 낱말로 안 드러나기 때문이다 —');
  말('   17번은 원을 쓰면서 「원」이라는 낱말을 한 번도 안 쓴다 (지문형이라 일부러 그렇게 만들었다).');
  말('   15번도 「진리집합이 원판이 된다」라 낱말이 없다.');
  말('   🔴 **대조표의 「도형」 칸을 사람이 채우고 사람이 센다.** 아래는 그 칸이 있는지만 본다.');
  const 대조표 = path.join(path.dirname(파일), '제안서', '전체-도구-대조표.md');
  if (!fs.existsSync(대조표)) {
    노랑('전체-도구-대조표.md 가 없다. 껍데기를 적을 자리가 없으면 이 병은 다시 난다');
  } else {
    const t = fs.readFileSync(대조표, 'utf8');
    const 칸 = ['형식', '발문 끝말', '답의 생김새', '도형'];
    const 없는칸 = 칸.filter((c) => !t.includes(c));
    if (없는칸.length) 빨강(`대조표에 껍데기 칸이 없다 — ${없는칸.join(' · ')}\n     🔴 도구 칸만 있으면 도구 이름만 다르면 통과한다. 그 구멍으로 7번·11번이 새어 나갔다`);
    else 말('   ✅ 대조표에 껍데기 칸 넷이 다 있다 (형식 · 발문 끝말 · 답의 생김새 · 도형)');
  }
}

말('\n' + '='.repeat(74));
말(`  🔴 RED ${RED} · 🟡 YELLOW ${YELLOW}`);
말('  🔴 이 도구는 「닮았다」고만 말한다. 같은 문항인지는 사람이 판정한다.');
말('  단일 출처: bank/통합관리-시스템-v1.md · 이 회차의 사례는');
말('             output/공통수학2/2026-2학기-와부고-재현-중간-2회/제안서/전체-도구-대조표.md §되풀이하지 마라');
process.exit(RED > 0 ? 1 : 0);
