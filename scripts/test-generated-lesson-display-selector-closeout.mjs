import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import { selectAutoGeneratedDisplayLessons } from "../src/domains/lessons/generatedLessonDisplaySelectors.js";

const preExamControl = {
  generatedKey: "generated_CONTROL_PRE_EXAM",
  lesson: {
    lessonId: "lesson_CONTROL_PRE_EXAM",
    lessonType: "preExam"
  },
  status: "create"
};
const createTarget = {
  generatedKey: "generated_TARGET_CREATE",
  lesson: {
    lessonId: "lesson_TARGET_CREATE",
    lessonType: "examPrep"
  },
  status: "create"
};
const syncedControl = {
  generatedKey: "generated_CONTROL_SYNCED",
  lesson: {
    lessonId: "lesson_CONTROL_SYNCED",
    lessonType: "examPrep"
  },
  status: "synced"
};
const updateTarget = {
  generatedKey: "generated_TARGET_UPDATE",
  lesson: {
    lessonId: "lesson_TARGET_UPDATE",
    lessonType: "examPrep"
  },
  status: "update"
};
const planItems = [
  preExamControl,
  createTarget,
  syncedControl,
  updateTarget
];
const inputSnapshot = structuredClone(planItems);
const displayLessons = selectAutoGeneratedDisplayLessons(planItems);

assert.deepEqual(displayLessons, [
  {
    ...createTarget.lesson,
    isExamPrepAutoLesson: true,
    isVirtualGeneratedLesson: true,
    generatedKey: createTarget.generatedKey
  },
  {
    ...updateTarget.lesson,
    isExamPrepAutoLesson: true,
    isVirtualGeneratedLesson: false,
    generatedKey: updateTarget.generatedKey
  }
]);
assert.notEqual(displayLessons[0], createTarget.lesson);
assert.notEqual(displayLessons[1], updateTarget.lesson);
assert.deepEqual(planItems, inputSnapshot);

const appSource = await readFile(
  new URL("../src/app/App.jsx", import.meta.url),
  "utf8"
);
const helperSource = await readFile(
  new URL(
    "../src/domains/lessons/generatedLessonDisplaySelectors.js",
    import.meta.url
  ),
  "utf8"
);
const modulePath =
  'from "../domains/lessons/generatedLessonDisplaySelectors.js"';
assert.equal(appSource.split(modulePath).length - 1, 1);
assert.equal(
  helperSource.split(
    "export function selectAutoGeneratedDisplayLessons("
  ).length - 1,
  1
);
assert.equal(
  appSource.split(
    "selectAutoGeneratedDisplayLessons(generatedLessonPlan)"
  ).length - 1,
  1
);

const selectorStart = appSource.indexOf(
  "const autoGeneratedDisplayLessons = useMemo("
);
const calendarStart = appSource.indexOf(
  "  const calendarLessons = useMemo(",
  selectorStart
);
const calendarEnd = appSource.indexOf(
  "  const monthlyRegularLessonOpenPlan = useMemo(",
  calendarStart
);
assert.ok(
  selectorStart >= 0 &&
    calendarStart > selectorStart &&
    calendarEnd > calendarStart
);

const selectorSource = appSource.slice(selectorStart, calendarStart);
assert.ok(
  selectorSource.includes(
    "() => selectAutoGeneratedDisplayLessons(generatedLessonPlan)"
  )
);
assert.ok(selectorSource.includes("[generatedLessonPlan]"));
assert.ok(!selectorSource.includes(".filter("));
assert.ok(!selectorSource.includes(".map("));

const calendarSource = appSource.slice(calendarStart, calendarEnd);
const calendarBoundaries = [
  "new Set(autoGeneratedDisplayLessons.flatMap(getGeneratedLessonIdentityKeys))",
  "const baseLessons = lessons.filter((lesson) =>",
  "!isLegacyExamPrepLesson(lesson)",
  "!getGeneratedLessonIdentityKeys(lesson).some((key) => autoDisplayKeys.has(key))",
  "return [...baseLessons, ...autoGeneratedDisplayLessons]",
  "[autoGeneratedDisplayLessons, lessons]"
];
let previousCalendarIndex = -1;
for (const boundary of calendarBoundaries) {
  const boundaryIndex = calendarSource.indexOf(
    boundary,
    previousCalendarIndex + 1
  );
  assert.ok(
    boundaryIndex > previousCalendarIndex,
    `generated lesson calendar merge order changed: ${boundary}`
  );
  previousCalendarIndex = boundaryIndex;
}

for (const forbiddenHelperEffect of [
  "useState",
  "useEffect",
  "fetch(",
  "postJson",
  "/api/",
  "setLessons",
  "setExamPrepRows",
  "persistExamPrepRows",
  "localStorage",
  "Supabase",
  "Solapi",
  "new Date",
  "Date.now",
  "Promise.all"
]) {
  assert.ok(
    !helperSource.includes(forbiddenHelperEffect),
    `generated lesson display selector closeout crossed a side effect: ${forbiddenHelperEffect}`
  );
}

console.log("generated lesson display selector boundary closeout passed");
