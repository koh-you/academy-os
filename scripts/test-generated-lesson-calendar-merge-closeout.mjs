import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import { mergeGeneratedCalendarLessons } from "../src/domains/lessons/generatedLessonCalendarMerge.js";

const keptTarget = {
  lessonId: "lesson_TARGET_KEEP",
  identityKeys: ["generated:keep"]
};
const legacyControl = {
  lessonId: "lesson_CONTROL_LEGACY",
  identityKeys: ["generated:legacy"],
  legacy: true
};
const duplicatePrimaryControl = {
  lessonId: "lesson_CONTROL_DUPLICATE_PRIMARY",
  identityKeys: ["generated:auto:create"]
};
const duplicateCompatibilityControl = {
  lessonId: "lesson_CONTROL_DUPLICATE_COMPATIBILITY",
  identityKeys: ["compat:auto:update"]
};
const noIdentityTarget = {
  lessonId: "lesson_TARGET_NO_IDENTITY",
  identityKeys: []
};
const autoCreateTarget = {
  identityKeys: ["generated:auto:create", "compat:auto:create"],
  lessonId: "lesson_TARGET_AUTO_CREATE"
};
const autoUpdateTarget = {
  identityKeys: ["generated:auto:update", "compat:auto:update"],
  lessonId: "lesson_TARGET_AUTO_UPDATE"
};
const lessons = [
  keptTarget,
  legacyControl,
  duplicatePrimaryControl,
  duplicateCompatibilityControl,
  noIdentityTarget
];
const autoGeneratedDisplayLessons = [
  autoCreateTarget,
  autoUpdateTarget
];
const lessonsSnapshot = structuredClone(lessons);
const autoSnapshot = structuredClone(autoGeneratedDisplayLessons);
const calendarLessons = mergeGeneratedCalendarLessons({
  autoGeneratedDisplayLessons,
  getIdentityKeys: (lesson) => lesson.identityKeys ?? [],
  isLegacyLesson: (lesson) => lesson.legacy === true,
  lessons
});

assert.deepEqual(calendarLessons, [
  keptTarget,
  noIdentityTarget,
  autoCreateTarget,
  autoUpdateTarget
]);
assert.equal(calendarLessons[0], keptTarget);
assert.equal(calendarLessons[1], noIdentityTarget);
assert.equal(calendarLessons[2], autoCreateTarget);
assert.equal(calendarLessons[3], autoUpdateTarget);
assert.deepEqual(lessons, lessonsSnapshot);
assert.deepEqual(autoGeneratedDisplayLessons, autoSnapshot);

const appSource = await readFile(
  new URL("../src/app/App.jsx", import.meta.url),
  "utf8"
);
const helperSource = await readFile(
  new URL(
    "../src/domains/lessons/generatedLessonCalendarMerge.js",
    import.meta.url
  ),
  "utf8"
);
const modulePath =
  'from "../domains/lessons/generatedLessonCalendarMerge.js"';
assert.equal(appSource.split(modulePath).length - 1, 1);
assert.equal(
  helperSource.split(
    "export function mergeGeneratedCalendarLessons("
  ).length - 1,
  1
);
assert.equal(
  appSource.split("mergeGeneratedCalendarLessons({").length - 1,
  1
);

const calendarStart = appSource.indexOf(
  "const calendarLessons = useMemo("
);
const calendarEnd = appSource.indexOf(
  "  const monthlyRegularLessonOpenPlan = useMemo(",
  calendarStart
);
assert.ok(calendarStart >= 0 && calendarEnd > calendarStart);
const calendarSource = appSource.slice(calendarStart, calendarEnd);
const appBoundaries = [
  "() => mergeGeneratedCalendarLessons({",
  "autoGeneratedDisplayLessons,",
  "getIdentityKeys: getGeneratedLessonIdentityKeys",
  "isLegacyLesson: isLegacyExamPrepLesson",
  "lessons",
  "[autoGeneratedDisplayLessons, currentGeneratedLessonSourceLessons]"
];
let previousAppIndex = -1;
for (const boundary of appBoundaries) {
  const boundaryIndex = calendarSource.indexOf(
    boundary,
    previousAppIndex + 1
  );
  assert.ok(
    boundaryIndex > previousAppIndex,
    `generated lesson calendar App boundary changed: ${boundary}`
  );
  previousAppIndex = boundaryIndex;
}
assert.ok(!calendarSource.includes("new Set("));
assert.ok(!calendarSource.includes(".filter("));

const mergeBoundaries = [
  "new Set(",
  "autoGeneratedDisplayLessons.flatMap(getIdentityKeys)",
  "const baseLessons = lessons.filter(",
  "!isLegacyLesson(lesson)",
  "!getIdentityKeys(lesson).some((key) => autoDisplayKeys.has(key))",
  "return [...baseLessons, ...autoGeneratedDisplayLessons]"
];
let previousMergeIndex = -1;
for (const boundary of mergeBoundaries) {
  const boundaryIndex = helperSource.indexOf(
    boundary,
    previousMergeIndex + 1
  );
  assert.ok(
    boundaryIndex > previousMergeIndex,
    `generated lesson calendar merge order changed: ${boundary}`
  );
  previousMergeIndex = boundaryIndex;
}

for (const forbiddenHelperEffect of [
  "useState",
  "useEffect",
  "fetch(",
  "postJson",
  "/api/",
  "setLessons",
  "setExamPrepRows",
  "persistExamPrepRows",
  "localStorage",
  "Supabase",
  "Solapi",
  "new Date",
  "Date.now",
  "Promise.all"
]) {
  assert.ok(
    !helperSource.includes(forbiddenHelperEffect),
    `generated lesson calendar merge closeout crossed a side effect: ${forbiddenHelperEffect}`
  );
}

