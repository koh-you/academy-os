import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";

function selectExistingAutoGeneratedDisplayLessons(planItems = []) {
  return planItems
    .filter(
      (item) =>
        item.lesson?.lessonType !== "preExam" &&
        (item.status === "create" || item.status === "update")
    )
    .map((item) => ({
      ...item.lesson,
      isExamPrepAutoLesson: true,
      isVirtualGeneratedLesson: item.status === "create",
      generatedKey: item.generatedKey
    }));
}

const preExamControl = {
  generatedKey: "generated_CONTROL_PRE_EXAM",
  lesson: {
    lessonId: "lesson_CONTROL_PRE_EXAM",
    lessonType: "preExam"
  },
  status: "create"
};
const createTarget = {
  generatedKey: "generated_TARGET_CREATE",
  lesson: {
    lessonId: "lesson_TARGET_CREATE",
    lessonType: "examPrep",
    marker: "TARGET_CREATE"
  },
  status: "create"
};
const syncedControl = {
  generatedKey: "generated_CONTROL_SYNCED",
  lesson: {
    lessonId: "lesson_CONTROL_SYNCED",
    lessonType: "examPrep"
  },
  status: "synced"
};
const updateTarget = {
  generatedKey: "generated_TARGET_UPDATE",
  lesson: {
    lessonId: "lesson_TARGET_UPDATE",
    lessonType: "examPrep",
    marker: "TARGET_UPDATE"
  },
  status: "update"
};
const protectedControl = {
  generatedKey: "generated_CONTROL_PROTECTED",
  lesson: {
    lessonId: "lesson_CONTROL_PROTECTED",
    lessonType: "examPrep"
  },
  status: "protected"
};
const planItems = [
  preExamControl,
  createTarget,
  syncedControl,
  updateTarget,
  protectedControl
];
const inputSnapshot = structuredClone(planItems);
const displayLessons =
  selectExistingAutoGeneratedDisplayLessons(planItems);

assert.deepEqual(displayLessons, [
  {
    ...createTarget.lesson,
    isExamPrepAutoLesson: true,
    isVirtualGeneratedLesson: true,
    generatedKey: createTarget.generatedKey
  },
  {
    ...updateTarget.lesson,
    isExamPrepAutoLesson: true,
    isVirtualGeneratedLesson: false,
    generatedKey: updateTarget.generatedKey
  }
]);
assert.notEqual(displayLessons[0], createTarget.lesson);
assert.notEqual(displayLessons[1], updateTarget.lesson);
assert.deepEqual(planItems, inputSnapshot);
assert.deepEqual(selectExistingAutoGeneratedDisplayLessons(), []);

const appSource = await readFile(
  new URL("../src/app/App.jsx", import.meta.url),
  "utf8"
);
const selectorStart = appSource.indexOf(
  "const autoGeneratedDisplayLessons = useMemo("
);
const selectorEnd = appSource.indexOf(
  "  const calendarLessons = useMemo(",
  selectorStart
);
assert.ok(selectorStart >= 0 && selectorEnd > selectorStart);
const selectorSource = appSource.slice(selectorStart, selectorEnd);
for (const selectorBoundary of [
  "const autoGeneratedDisplayLessons = useMemo(",
  "() => generatedLessonPlan",
  'item.lesson?.lessonType !== "preExam"',
  'item.status === "create" || item.status === "update"',
  "isExamPrepAutoLesson: true",
  'isVirtualGeneratedLesson: item.status === "create"',
  "generatedKey: item.generatedKey",
  "[generatedLessonPlan]"
]) {
  assert.ok(
    selectorSource.includes(selectorBoundary),
    `missing generated lesson display selector boundary: ${selectorBoundary}`
  );
}
for (const forbiddenEffect of [
  "setLessons(",
  "setExamPrepRows(",
  "persistExamPrepRows(",
  "postJson",
  "/api/",
  "localStorage",
  "Solapi"
]) {
  assert.ok(
    !selectorSource.includes(forbiddenEffect),
    `generated lesson display selector crossed an effect: ${forbiddenEffect}`
  );
}

const calendarStart = appSource.indexOf(
  "const calendarLessons = useMemo(",
  selectorEnd
);
const calendarEnd = appSource.indexOf(
  "  const monthlyRegularLessonOpenPlan = useMemo(",
  calendarStart
);
assert.ok(calendarStart >= 0 && calendarEnd > calendarStart);
const calendarSource = appSource.slice(calendarStart, calendarEnd);
for (const consumerBoundary of [
  "new Set(autoGeneratedDisplayLessons.flatMap(getGeneratedLessonIdentityKeys))",
  "!isLegacyExamPrepLesson(lesson)",
  "!getGeneratedLessonIdentityKeys(lesson).some((key) => autoDisplayKeys.has(key))",
  "return [...baseLessons, ...autoGeneratedDisplayLessons]",
  "[autoGeneratedDisplayLessons, lessons]"
]) {
  assert.ok(
    calendarSource.includes(consumerBoundary),
    `missing generated lesson display consumer: ${consumerBoundary}`
  );
}

