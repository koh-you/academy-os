import assert from "node:assert/strict";
import { newBlogDraft, seedScore, buildChatPrompt, parseChatResult, finalizeDraft, isNaverPostUrl } from "../src/domains/blogContent/blogHybridModel.js";
const d = newBlogDraft();
assert.throws(() => buildChatPrompt(d));
const seed = seedScore({ scoreRecordId: "private-id", score: 0, grade: 2, subject: "수학Ⅰ" }, { name: "안서준", schoolName: "창동고", grade: "2" });
assert.equal(seed.displayName, "안○○"); assert.equal(seed.achievement, "0점 / 2등급");
const ready = { ...d, ...seed, exam: "1학기 기말", consent: "agreed", confirmed: true };
const prompt = buildChatPrompt(ready);
assert.ok(prompt.includes("0점")); assert.ok(!prompt.includes("private-id")); assert.ok(!prompt.includes("안서준"));
assert.throws(() => buildChatPrompt({ ...ready, assets: "https://example.com/photo" }));
assert.throws(() => buildChatPrompt({ ...ready, consent: "declined" }));
assert.throws(() => buildChatPrompt({ ...ready, consent: "none" }));
const result = parseChatResult('```json\n{"title":"제목","body":"본문\\n두 번째 줄"}\n```');
assert.equal(result.body, "본문\n두 번째 줄");
assert.throws(() => parseChatResult('{"title":"제목","body":"본문","source":{}}'));
assert.throws(() => parseChatResult('{"title":"제목"}'));
const final = finalizeDraft({ ...ready, copy: { ...d.copy, ...result } });
const again = finalizeDraft({ ...final, copy: { ...final.copy, body: "수정" } });
assert.equal(again.versions[0].copy.body, result.body); assert.equal(again.versions.length, 2);
assert.equal(isNaverPostUrl("https://blog.naver.com/koh_you_math/1234"), true);
assert.equal(isNaverPostUrl("https://blog.naver.com.evil.example/user/123"), false);
assert.equal(isNaverPostUrl("javascript:alert(1)"), false);
console.log("blog hybrid: facts, consent, export privacy, import and version history passed");
